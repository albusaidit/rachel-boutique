export type AdminDict = (typeof dict)["ar"];

type Ctx = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  theme: Theme;
  setTheme: (t: Theme) => void;
  toggleTheme: () => void;
  d: AdminDict;
};

const AdminLocaleContext = createContext<Ctx | null>(null);

export function AdminLocaleProvider({
  children,
  className = "",
}: {
  children: React.ReactNode;
  className?: string;
}) {
  const [locale, setLocaleState] = useState<Locale>("en");
  const [theme, setThemeState] = useState<Theme>("light");

  useEffect(() => {
    try {
      const sl = localStorage.getItem(LOCALE_KEY) as Locale | null;
      if (sl && (LOCALES as readonly string[]).includes(sl)) setLocaleState(sl);
      const st = localStorage.getItem(THEME_KEY) as Theme | null;
      if (st === "dark" || st === "light") setThemeState(st);
    } catch {}
  }, []);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem(LOCALE_KEY, l);
    } catch {}
  }, []);

  const setTheme = useCallback((t: Theme) => {
    setThemeState(t);
    try {
      localStorage.setItem(THEME_KEY, t);
    } catch {}
  }, []);

  const toggleTheme = useCallback(
    () => setTheme(theme === "dark" ? "light" : "dark"),
    [theme, setTheme],
  );

  const value = useMemo<Ctx>(
    () => ({
      locale,
      setLocale,
      theme,
      setTheme,
      toggleTheme,
      d: dict[locale] as AdminDict,
    }),
    [locale, setLocale, theme, setTheme, toggleTheme],
  );

  return (
    <AdminLocaleContext.Provider value={value}>
      <div
        dir={dict[locale].dir}
        lang={dict[locale].lang}
        data-theme={theme}
        className={className}
        suppressHydrationWarning
      >
        {children}
      </div>
    </AdminLocaleContext.Provider>
  );
}

export function useAdminLocale(): Ctx {
  const ctx = useContext(AdminLocaleContext);
  if (!ctx) throw new Error("useAdminLocale must be used within AdminLocaleProvider");
  return ctx;
}
